const signed = (ko: boolean, value: number) => {
  const amount = `${Math.abs(value * 100).toFixed(1)}%`;
  if (ko) return `${amount} ${value >= 0 ? "늘었" : "줄었"}`;
  return `${value >= 0 ? "rose" : "fell"} ${amount}`;
};

