export type MessageKey = keyof (typeof MESSAGES)["ko"];
type Lang = keyof typeof MESSAGES;
const FALLBACK: Lang = "en";

const LangContext = createContext<string | null>(null);

export function LangProvider({ lang, children }: { lang?: string; children: ReactNode }) {
  return <LangContext.Provider value={lang ?? null}>{children}</LangContext.Provider>;
}

const isLang = (value: string): value is Lang => value in MESSAGES;

export function resolveLocale(context: string | null) {
  const page = typeof document === "undefined" ? "" : document.documentElement.lang;
  return context || page || FALLBACK;
}

export function useI18n() {
  const locale = resolveLocale(useContext(LangContext));
  const base = locale.split("-")[0].toLowerCase();
  const lang: Lang = isLang(base) ? base : FALLBACK;
  const text = (key: MessageKey, vars: Record<string, string | number> = {}) =>
    MESSAGES[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
  return { lang, locale, text };
}

export const languages = Object.keys(MESSAGES);
